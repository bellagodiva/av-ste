#!/usr/bin/env python
"""
AV-STE demo comparison — two tables per noise type.

For each noise type (speech / nonspeech) at −10 dB SNR we compare three conditions:
  1. Clean audio           → Mimi tokens (upper bound)
  2. Noisy audio           → Mimi tokens (baseline)
  3. Noisy audio + AV-STE → enhanced tokens (ours)

Table A — Mimi-decoded quality
  Semantic-token accuracy (cb0 vs. clean reference) is our primary metric --
  it's what AV-STE is trained on and what Moshi actually consumes. WER of the
  Mimi-decoded audio via Whisper is reported alongside as a secondary,
  human-legible diagnostic, not the main result.

Table B — Moshi streaming generation
  Follows moshi_lrs3_avste_inference.py exactly:
    1. Build [N_pre silence | audio | N_post silence] waveform
    2. Stream-encode with Mimi frame-by-frame → codes_list
    3. For AV-STE: replace CB0 for utterance frames with predicted tokens (25 Hz → 12.5 Hz)
    4. Feed codes_list to Moshi LM with streaming Mimi decode
    5. Trim pre-silence from output

AV-STE token predictions are loaded from examples/predictions_*.json, generated by
infer_lrs3_dialog_test.sh (av_4lookahead_crossattn_soft_gate checkpoint).

Samples:
  Speech noise −10 dB: rP7nmdDA1Fg_00006 — "I THINK WHAT THAT MEANS IS THAT PEOPLE
                        JUST COULDN'T SEE WHAT WAS IN FRONT OF THEM"
  Speech noise  −5 dB: ta2Wvy9FSgA_00003 — "BUT IF THEY DON'T STAY IN PARIS THE
                        INTERNATIONAL PRESSURE WILL BE OVERWHELMING"
  Ambient noise −10 dB: w1R4F9sSoow_00003 — "WE HAVE IDEAS FOR HOW TO MAKE THINGS
                         BETTER AND I WANT TO SHARE THREE OF THEM"
  Ambient noise  −5 dB: RplnSVTzvnU_00003 — "WE CAN CREATE A DECENTRALIZED DATABASE
                         THAT HAS THE SAME EFFICIENCY OF A MONOPOLY"

Usage:
  python scripts/compare_demo.py [--save_audio]

Run with the avste conda env:
  conda run -n avste python scripts/compare_demo.py
"""
